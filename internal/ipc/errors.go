package ipc

import "errors"

// RequestError carries only an allowlisted public category. It never contains
// native input, a selected filename, an OS error or provider response text.
type RequestError struct{ code string }

func (e *RequestError) Error() string { return e.code }

func SafeErrorCode(code string) string {
	switch code {
	case "PASSWORD_POLICY", "INPUT_TOO_LONG", "PASSWORD_MISMATCH", "INVALID_MNEMONIC",
		"BACKUP_DESTINATION_UNSAFE", "BACKUP_EXISTS", "BACKUP_WRITE_FAILED", "BACKUP_VERIFY_FAILED",
		"RESTORE_SOURCE_UNSAFE", "REQUEST_CANCELLED",
		"ADDRESS_BOOK_INVALID_INPUT", "ADDRESS_BOOK_INVALID_ADDRESS", "ADDRESS_BOOK_DUPLICATE_NAME",
		"ADDRESS_BOOK_DUPLICATE_RECIPIENT", "ADDRESS_BOOK_LIMIT", "ADDRESS_BOOK_STALE",
		"ADDRESS_BOOK_UNAVAILABLE", "ADDRESS_BOOK_WRITE_FAILED":
		return code
	case "TON_RPC_RATE_LIMITED", "TON_DEPLOYMENT_UNAVAILABLE", "TON_DEPLOYMENT_RECORD_FAILED", "TON_DEPLOYMENT_INVALID_PLAN", "TON_DEPLOYMENT_PENDING":
		return code
	case "PAYMENT_QUOTE_INVALID_INPUT", "PAYMENT_QUOTE_BALANCE_UNAVAILABLE", "PAYMENT_QUOTE_INSUFFICIENT_FUNDS", "PAYMENT_QUOTE_UNAVAILABLE", "PAYMENT_QUOTE_INVALID_PLAN", "PAYMENT_QUOTE_UNSTABLE", "PAYMENT_PENDING", "PAYMENT_PENDING_UNAVAILABLE":
		return code
	case "ACCOUNT_RECOVERY_INVALID_RANGE", "ACCOUNT_RECOVERY_LIMIT", "ACCOUNT_RECOVERY_DERIVATION", "ACCOUNT_RECOVERY_STORAGE", "ACCOUNT_RECOVERY_STALE":
		return code
	case "EXCHANGE_STATE_INVALID", "EXCHANGE_DEPOSIT_ROUTE_UNAVAILABLE", "EXCHANGE_DEPOSIT_SUSPENDED", "EXCHANGE_DEPOSIT_BELOW_MINIMUM", "EXCHANGE_DEPOSIT_ADDRESS_INVALID", "EXCHANGE_DEPOSIT_MASTER_REQUIRED":
		return code
	case "EXCHANGE_DEPOSIT_NETWORK_MISMATCH", "EXCHANGE_DEPOSIT_CONTRACT_MISMATCH", "EXCHANGE_DEPOSIT_MEMO_INVALID":
		return code
	case "EXCHANGE_WIZARD_STALE", "EXCHANGE_DEPOSIT_PENDING", "EXCHANGE_UNIFIED_REQUIRED", "EXCHANGE_TRANSFER_PERMISSION", "EXCHANGE_FUNDING_INSUFFICIENT", "EXCHANGE_UNIFIED_INSUFFICIENT", "EXCHANGE_WITHDRAW_UNAVAILABLE":
		return code
	case "EXCHANGE_DEPOSIT_DESTINATION_CHANGED", "EXCHANGE_WIZARD_PERMISSIONS":
		return code
	case "REQUEST_DENIED", "INVALID_ARGUMENT", "WALLET_LOCKED", "AUTHENTICATION_FAILED", "ACCESS_DENIED",
		"STORAGE_PERMISSION_DENIED", "STORAGE_UNAVAILABLE", "STORAGE_CORRUPT",
		"NETWORK_UNAVAILABLE", "NETWORK_TIMEOUT", "NETWORK_TLS_FAILED",
		"PROVIDER_RATE_LIMITED", "PROVIDER_AUTHENTICATION_FAILED", "PROVIDER_ACCESS_DENIED",
		"PROVIDER_UNAVAILABLE", "PROVIDER_INVALID_RESPONSE", "PROVIDER_REQUEST_REJECTED", "PROVIDER_REDIRECT_DENIED", "PROVIDER_CLOCK_SKEW",
		"CHAIN_DATA_INVALID":
		return code
	default:
		if _, _, ok := ExchangeReadErrorParts(code); ok {
			return code
		}
		return "REQUEST_FAILED_STATE_UNKNOWN"
	}
}

func NewRequestError(code string) error { return &RequestError{SafeErrorCode(code)} }

func PublicErrorCode(err error) string {
	if err == nil {
		return ""
	}
	var failure *RequestError
	if errors.As(err, &failure) && failure != nil {
		return SafeErrorCode(failure.code)
	}
	return "REQUEST_FAILED_STATE_UNKNOWN"
}
